#!/usr/bin/env python3
"""Prepare and run a one-step CPU fixture for the Issue #74 Hub QA pass.

The default action only writes a fresh, local fixture below ``--output-dir``.
``--train`` runs one SFT step in a child process with CUDA/ROCm hidden and
downloads its public tiny base model without credentials. Hub writes are
impossible unless both ``--push-as`` and ``--verify-hub`` are provided. In
that mode the script first verifies that the destination model repository
already exists, is private, and has no ``checkpoint-1`` branch; it then verifies the
newly pushed branch after training.

This is a QA fixture, not a claim that a local CPU run proves Hub behavior.
It deliberately never creates a Hub repository, stores a token, or uploads by
default.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Sequence

from rich.console import Console

console = Console()

MODEL_ID = "hf-internal-testing/tiny-random-gpt2"
CHECKPOINT_NAME = "checkpoint-1"
_CPU_ENVIRONMENT = {
    "ACCELERATE_USE_CPU": "true",
    "CUDA_VISIBLE_DEVICES": "-1",
    "HIP_VISIBLE_DEVICES": "",
    "ROCR_VISIBLE_DEVICES": "",
}
_REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
_SOURCE_ROOT = _REPOSITORY_ROOT / "src"


@dataclass(frozen=True)
class FixturePaths:
    """All local artifacts belonging to one fresh fixture directory."""

    root: Path
    data: Path
    config: Path
    output: Path
    command: Path
    report: Path


def fixture_paths(output_dir: Path) -> FixturePaths:
    """Construct paths without creating or resolving anything on disk."""
    return FixturePaths(
        root=output_dir,
        data=output_dir / "train.jsonl",
        config=output_dir / "soup.yaml",
        output=output_dir / "output",
        command=output_dir / "cpu-train-command.txt",
        report=output_dir / "cpu-fixture-report.json",
    )


def _as_yaml_string(value: str) -> str:
    """Use JSON's quoted-string subset, which YAML accepts without ambiguity."""
    return json.dumps(value)


def _config_text(paths: FixturePaths) -> str:
    """Return a one-row config that produces exactly one optimizer/save step."""
    return f"""# Generated by benchmarks/harness/hf_hub_cpu_fixture.py.
# One row x batch size one x one epoch gives exactly one optimizer step.
base: {MODEL_ID}
task: sft

data:
  train: {_as_yaml_string(str(paths.data))}
  format: chatml
  chat_template: chatml
  val_split: 0.0
  max_length: 64

training:
  epochs: 1
  lr: 5e-4
  batch_size: 1
  gradient_accumulation_steps: 1
  lora:
    r: 4
    alpha: 8
  quantization: none
  save_steps: 1
  logging_steps: 1

output: {_as_yaml_string(str(paths.output))}
"""


def _data_text() -> str:
    """Return one valid ChatML row without a task-specific quality claim."""
    row = {
        "messages": [
            {"role": "user", "content": "Reply with the word soup."},
            {"role": "assistant", "content": "soup"},
        ]
    }
    return json.dumps(row, ensure_ascii=False) + "\n"


def build_train_command(paths: FixturePaths, push_as: str | None = None) -> list[str]:
    """Build the exact child command without invoking a shell."""
    command = [
        sys.executable,
        "-m",
        "soup_cli.cli",
        "train",
        "--config",
        str(paths.config),
        "--yes",
    ]
    if push_as is not None:
        command.extend(("--push-as", push_as))
    return command


def prepare_fixture(output_dir: str | Path, push_as: str | None = None) -> FixturePaths:
    """Write a fresh fixture directory and refuse every overwrite attempt."""
    root = Path(output_dir).expanduser().absolute()
    if root.exists() or root.is_symlink():
        raise FileExistsError(
            f"Refusing to overwrite existing fixture directory: {root}. Choose a new --output-dir."
        )

    paths = fixture_paths(root)
    root.mkdir(parents=True, exist_ok=False)
    try:
        paths.data.write_text(_data_text(), encoding="utf-8")
        paths.config.write_text(_config_text(paths), encoding="utf-8")
        command = build_train_command(paths, push_as)
        paths.command.write_text(
            " ".join(json.dumps(part) for part in command) + "\n", encoding="utf-8"
        )
    except Exception:
        # The directory is deliberately left intact for inspection.  It remains
        # fresh, and a retry must use a new path instead of overwriting it.
        raise
    return paths


def cpu_environment(push_as: str | None = None) -> dict[str, str]:
    """Return a CPU-only child environment that imports this checkout's Soup."""
    environment = os.environ.copy()
    environment.update(_CPU_ENVIRONMENT)
    if push_as is None:
        # A local-only run downloads a public model and must not expose an
        # unrelated caller credential to its child process. Hugging Face Hub
        # otherwise sends a cached login on read requests by default.
        environment.pop("HF_TOKEN", None)
        environment.pop("HUGGINGFACE_HUB_TOKEN", None)
        environment["HF_HUB_DISABLE_IMPLICIT_TOKEN"] = "1"
    current_python_path = environment.get("PYTHONPATH", "")
    source_path = str(_SOURCE_ROOT)
    environment["PYTHONPATH"] = (
        source_path if not current_python_path else source_path + os.pathsep + current_python_path
    )
    return environment


def _prefer_local_source() -> None:
    """Make parent-side Hub checks import this checkout, not another editable Soup."""
    source_path = str(_SOURCE_ROOT)
    if not sys.path or sys.path[0] != source_path:
        sys.path.insert(0, source_path)


def _refuse_mps_acceleration() -> None:
    """Decline macOS MPS rather than call this fixture CPU while it is not."""
    if sys.platform != "darwin":
        return
    import torch

    if torch.backends.mps.is_available():
        raise RuntimeError(
            "This fixture refuses to label an MPS run as CPU. Soup train has no "
            "explicit CPU device flag; run it on a CPU-only host instead."
        )


def verify_private_destination(repo_id: str) -> None:
    """Require a private destination with no stale checkpoint branch."""
    _prefer_local_source()
    from soup_cli.utils.hf import get_hf_api, resolve_endpoint, resolve_token, validate_repo_id

    validate_repo_id(repo_id)
    token = resolve_token()
    if token is None:
        raise RuntimeError(
            "--verify-hub requires an HF write token via HF_TOKEN or a cached login."
        )
    api = get_hf_api(token=token, endpoint=resolve_endpoint())
    try:
        info = api.model_info(repo_id)
    except Exception as exc:
        raise RuntimeError(
            "Refusing --push-as because the destination must be pre-created as a private "
            f"model repository: {repo_id!r}."
        ) from exc
    if not bool(getattr(info, "private", False)):
        raise RuntimeError(
            f"Refusing --push-as to non-private repository {repo_id!r}. "
            "Create a new private model repository first."
        )
    try:
        refs = api.list_repo_refs(repo_id)
    except Exception as exc:
        raise RuntimeError(
            f"Could not inspect existing branches in private destination {repo_id!r}."
        ) from exc
    branches = {str(branch.name) for branch in getattr(refs, "branches", [])}
    if CHECKPOINT_NAME in branches:
        raise RuntimeError(
            f"Refusing --push-as because private destination {repo_id!r} already has "
            f"a {CHECKPOINT_NAME!r} branch. Use a fresh repository or remove that branch "
            "before this one-step verification."
        )


def verify_remote_checkpoint(repo_id: str) -> dict[str, Any]:
    """Read back the checkpoint branch that the callback is expected to upload."""
    _prefer_local_source()
    from soup_cli.utils.hf import get_hf_api, resolve_endpoint, resolve_token

    token = resolve_token()
    if token is None:
        raise RuntimeError("HF token vanished before remote checkpoint verification.")
    api = get_hf_api(token=token, endpoint=resolve_endpoint())
    refs = api.list_repo_refs(repo_id)
    branches = {str(branch.name) for branch in getattr(refs, "branches", [])}
    if CHECKPOINT_NAME not in branches:
        raise RuntimeError(
            f"Remote repository has no {CHECKPOINT_NAME!r} branch after training. "
            "The training exit status alone is not a Hub push pass."
        )
    files = sorted(api.list_repo_files(repo_id, revision=CHECKPOINT_NAME))
    has_weights = any(name in {"adapter_model.safetensors", "adapter_model.bin"} for name in files)
    required = {"adapter_config.json", "trainer_state.json"}
    missing = sorted(required.difference(files))
    if missing or not has_weights:
        if not has_weights:
            missing.append("adapter weights")
        detail = ", ".join(missing)
        raise RuntimeError(f"Remote {CHECKPOINT_NAME!r} is incomplete; missing {detail}.")
    return {"branch": CHECKPOINT_NAME, "file_count": len(files)}


def verify_local_artifacts(paths: FixturePaths) -> dict[str, Any]:
    """Ensure a successful local child process wrote the expected saved artifacts."""
    adapter_config = paths.output / "adapter_config.json"
    adapter_weights = [
        paths.output / "adapter_model.safetensors",
        paths.output / "adapter_model.bin",
    ]
    checkpoint = paths.output / CHECKPOINT_NAME
    has_adapter_weights = any(candidate.is_file() for candidate in adapter_weights)
    if not adapter_config.is_file() or not has_adapter_weights:
        raise RuntimeError("Training did not produce a loadable adapter in the fixture output.")
    if not checkpoint.is_dir() or not (checkpoint / "trainer_state.json").is_file():
        raise RuntimeError(f"Training did not produce {CHECKPOINT_NAME}/trainer_state.json.")
    return {
        "adapter_config": adapter_config.name,
        "checkpoint": CHECKPOINT_NAME,
        "checkpoint_has_trainer_state": True,
    }


def _verify_cpu_child_environment(environment: dict[str, str]) -> None:
    """Fail closed unless a fresh child reports that CUDA is unavailable."""
    completed = subprocess.run(
        [sys.executable, "-c", "import torch; print(torch.cuda.is_available())"],
        env=environment,
        check=False,
        capture_output=True,
        text=True,
    )
    reported = completed.stdout.strip().splitlines()
    cuda_available = reported[-1] if reported else ""
    if completed.returncode != 0:
        stderr_lines = str(getattr(completed, "stderr", "")).strip().splitlines()
        detail = f" Last stderr line: {stderr_lines[-1]}" if stderr_lines else ""
        raise RuntimeError(
            "Could not verify CPU-only training: the Torch CUDA visibility probe "
            f"exited with status {completed.returncode}.{detail}"
        )
    if cuda_available != "False":
        observed = repr(cuda_available) if cuda_available else "no CUDA availability result"
        raise RuntimeError(
            "CUDA remained visible in the CPU fixture child process; refusing to run "
            f"a fixture labelled CPU-only (probe reported {observed})."
        )


def run_training(paths: FixturePaths, push_as: str | None) -> dict[str, Any]:
    """Launch Soup training in a CPU-only child and verify its local artifacts."""
    _refuse_mps_acceleration()
    command = build_train_command(paths, push_as)
    environment = cpu_environment(push_as)
    _verify_cpu_child_environment(environment)
    completed = subprocess.run(
        command,
        cwd=paths.root,
        env=environment,
        check=False,
    )
    if completed.returncode != 0:
        raise RuntimeError(f"CPU training exited with status {completed.returncode}.")
    return verify_local_artifacts(paths)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir", required=True, help="Fresh directory to create for this run"
    )
    parser.add_argument(
        "--train",
        action="store_true",
        help="Run the one-step CPU child process after preparing local files",
    )
    parser.add_argument(
        "--push-as",
        help="Existing private HF model repository for the opt-in checkpoint push",
    )
    parser.add_argument(
        "--verify-hub",
        action="store_true",
        help="Pre-check the private repo and verify remote checkpoint-1 after training",
    )
    parser.add_argument("--json", action="store_true", help="Emit the local result as JSON")
    return parser


def _write_result(result: dict[str, Any], json_output: bool) -> None:
    if json_output:
        console.print(json.dumps(result, indent=2, sort_keys=True))
        return
    console.print(f"[green]Prepared CPU fixture:[/] {result['fixture_dir']}")
    if result["trained"]:
        console.print("[green]One local CPU training step completed.[/]")
    else:
        console.print("[yellow]Prepared only; pass --train to run the CPU step.[/]")


def _write_report(paths: FixturePaths, result: dict[str, Any]) -> None:
    """Persist an attempted fixture result after its fresh directory exists."""
    paths.report.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if args.push_as and not args.train:
        _parser().error("--push-as requires --train")
    if args.push_as and not args.verify_hub:
        _parser().error("--push-as requires --verify-hub to prevent a public test repository")
    if args.verify_hub and not args.push_as:
        _parser().error("--verify-hub requires --push-as")

    paths: FixturePaths | None = None
    result: dict[str, Any] = {}
    try:
        if args.verify_hub:
            verify_private_destination(args.push_as)
        paths = prepare_fixture(args.output_dir, push_as=args.push_as)
        result = {
            "fixture_dir": str(paths.root),
            "model": MODEL_ID,
            "trained": bool(args.train),
            "hub_verified": False,
        }
        if args.train:
            result["local_artifacts"] = run_training(paths, args.push_as)
        if args.verify_hub:
            result["remote_checkpoint"] = verify_remote_checkpoint(args.push_as)
            result["hub_verified"] = True
        _write_report(paths, result)
    except (FileExistsError, OSError, RuntimeError, ValueError) as exc:
        if paths is not None:
            result["hub_verified"] = False
            result["error"] = str(exc)
            try:
                _write_report(paths, result)
            except OSError:
                pass
        console.print(f"CPU fixture failed: {exc}", style="red", markup=False)
        return 1

    _write_result(result, args.json)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
