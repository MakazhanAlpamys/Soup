#: The rule, as written in the record before the first run (nats per token).
CONTROL_TOL = 1e-3
RELOAD_TOL = 1e-2
MIN_FORGET_RISE = 0.5
MIN_SELECTIVITY = 0.5
MAX_RETAIN_RISE = 0.25


def _write_rows(path: Path, rows) -> None:
    path.write_text(
        "".join(json.dumps({"prompt": p, "completion": c}) + "\n" for p, c in rows),
        encoding="utf-8",
    )


def _config_text(model: str, seed: int, out: str) -> str:
    import yaml

    return yaml.safe_dump({
        "base": model,
        "task": "unlearn",
        "backend": "mlx",
        "data": {
            "train": "data/forget_train.jsonl",
            "forget_set": "data/forget_train.jsonl",
            "retain_set": "data/retain_train.jsonl",
            "max_length": MAX_LENGTH,
        },
        "training": {**TRAINING, "seed": seed},
        "output": out,
    }, sort_keys=False)


def score(model, tokenizer) -> dict:
    """Per row ``(summed NLL, scored tokens)`` of every set, one row at a time."""
    import mlx.core as mx
    import numpy as np

    from soup_cli.trainer.mlx_unlearn import build_unlearn_example

    model.eval()
    out = {}
    for name, rows in SETS.items():
        per_row = []
        for prompt, target in rows:
            ex = build_unlearn_example(tokenizer, prompt, target, max_length=MAX_LENGTH)
            ids = np.array(ex.ids)
            logits = model(mx.array(ids[None, :-1])).astype(mx.float32)
            mx.eval(logits)
            lg = np.array(logits[0]).astype(np.float64)
            top = lg.max(-1, keepdims=True)
            logsm = lg - top - np.log(np.exp(lg - top).sum(-1, keepdims=True))
            start = max(1, ex.target_start)
            positions = np.arange(start, len(ids))
            nll = -logsm[positions - 1, ids[positions]].sum()
            per_row.append([float(nll), int(len(positions))])
        out[name] = per_row
    return out


def per_token(rows) -> float:
    return sum(r[0] for r in rows) / sum(r[1] for r in rows)


def _score_arm(model_dir: str, arm: str, adapter: str | None, seed: int, out: Path) -> dict:
    """One arm, in a fresh process of this file."""
    cmd = [sys.executable, __file__, "score", "--model", model_dir, "--arm", arm,
           "--seed", str(seed), "--json", str(out)]
    if adapter:
        cmd += ["--adapter", adapter]
    subprocess.run(cmd, check=True, timeout=1800)
    return json.loads(out.read_text())


def _score_main(args) -> None:
    import mlx.core as mx
    from mlx_lm import load

    if args.arm == "adapter":
        model, tokenizer = load(args.model, adapter_path=args.adapter)
    else:
        model, tokenizer = load(args.model)
        if args.arm == "untrained":
            from mlx_lm.tuner.utils import linear_to_lora_layers

            meta = json.loads((Path(args.adapter) / "adapter_config.json").read_text())
            model.freeze()
            mx.random.seed(args.seed)
            linear_to_lora_layers(model, meta["num_layers"], meta["lora_parameters"])
    Path(args.json).write_text(json.dumps(score(model, tokenizer)))


def verdict(seeds: dict) -> dict:
    """The record's rule, applied to every seed; PASS only if every check holds."""
    checks = {}
    for seed, s in seeds.items():
        base, ctrl, trained, inproc = s["base"], s["untrained"], s["adapter"], s["in_process"]
        d = {k: per_token(trained[k]) - per_token(base[k]) for k in SETS}
        checks[seed] = {
            "dispatch": s["dispatch"] == "MLXSimNPOTrainerWrapper",
            "updates": s["updates"] == s["expected_updates"],
            "control": all(abs(per_token(ctrl[k]) - per_token(base[k])) <= CONTROL_TOL
                           for k in SETS),
            "reload": all(abs(per_token(trained[k]) - per_token(inproc[k])) <= RELOAD_TOL
                          for k in SETS),
            "forget_rise": d["forget_heldout"] >= MIN_FORGET_RISE,
            "selectivity": d["forget_heldout"] - d["retain_heldout"] >= MIN_SELECTIVITY,
            "retain_bound": d["retain_heldout"] <= MAX_RETAIN_RISE,
        }
    passed = all(all(c.values()) for c in checks.values())
    return {"verdict": "PASS" if passed else "FAIL", "checks": checks}


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def _run_main(args) -> None:
    import mlx.core as mx
    import mlx_lm

    from soup_cli.config.loader import load_config_from_string
    from soup_cli.trainer.dispatch import build_trainer
    from soup_cli.trainer.mlx_unlearn import MLXSimNPOTrainerWrapper

    model_dir = str(Path(args.model).resolve())
    out = Path(args.out).resolve()
    (out / "data").mkdir(parents=True, exist_ok=False)
    for name, rows in SETS.items():
        _write_rows(out / "data" / f"{name}.jsonl", rows)
    os.chdir(out)

    repo = Path(__file__).resolve().parents[2]
    evidence = {
        "issue": 2005,
        "model": {"path": model_dir, "revision": args.revision,
                  "model.safetensors sha256": _sha256(Path(model_dir) / "model.safetensors")},
        "source": subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"],
                                 capture_output=True, text=True, check=True).stdout.strip(),
        "source_dirty": bool(subprocess.run(
            ["git", "-C", str(repo), "status", "--porcelain", "--", "src"],
            capture_output=True, text=True, check=True).stdout.strip()),
        "versions": {"python": platform.python_version(), "mlx": mx.__version__,
                     "mlx_lm": mlx_lm.__version__, "macos": platform.mac_ver()[0],
                     "machine": platform.machine()},
        "training": TRAINING, "max_length": MAX_LENGTH,
        "rule": {"control_tol": CONTROL_TOL, "reload_tol": RELOAD_TOL,
                 "min_forget_rise": MIN_FORGET_RISE, "min_selectivity": MIN_SELECTIVITY,
                 "max_retain_rise": MAX_RETAIN_RISE},
        "seeds": {},
    }
    base = _score_arm(model_dir, "base", None, 0, out / "score-base.json")
    for seed in args.seeds:
        adapter = f"seed-{seed}"
        cfg = load_config_from_string(_config_text(model_dir, seed, adapter))
        wrapper = build_trainer(cfg)
        # Dispatch is asserted before anything is measured.
        if type(wrapper) is not MLXSimNPOTrainerWrapper:
            raise SystemExit(f"dispatched to {type(wrapper).__name__}, not the MLX SimNPO trainer")
        mx.reset_peak_memory()
        wrapper.setup()
        t0 = time.perf_counter()
        result = wrapper.train()
        wall = time.perf_counter() - t0
        peak = mx.get_peak_memory() / 1e9
        in_process = score(wrapper.model, wrapper.tokenizer)
        del wrapper
        per_epoch = math.ceil(len(FORGET_TRAIN) / TRAINING["batch_size"])
        expected = math.ceil(per_epoch * TRAINING["epochs"]
                             / TRAINING["gradient_accumulation_steps"])
        evidence["seeds"][str(seed)] = {
            "dispatch": "MLXSimNPOTrainerWrapper",
            "result": {k: v for k, v in result.items() if isinstance(v, (int, float, str))},
            "updates": result.get("updates"),
            "expected_updates": expected,
            "train_seconds": wall,
            "peak_memory_gb": peak,
            "in_process": in_process,
            "base": base,
            "untrained": _score_arm(model_dir, "untrained", adapter, seed,
                                    out / f"score-untrained-{seed}.json"),
            "adapter": _score_arm(model_dir, "adapter", adapter, seed,
                                  out / f"score-adapter-{seed}.json"),
        }
    evidence["outcome"] = verdict(evidence["seeds"])
    (out / "evidence.json").write_text(json.dumps(evidence, indent=2))
    for seed, s in evidence["seeds"].items():
        row = "  ".join(
            f"{k} {per_token(s['base'][k]):.3f}->{per_token(s['adapter'][k]):.3f}" for k in SETS
        )
        print(f"seed {seed}: {row}  ({s['train_seconds']:.1f} s, "
              f"peak {s['peak_memory_gb']:.2f} GB)")
    print(json.dumps(evidence["outcome"], indent=2))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="mode", required=True)
    run = sub.add_parser("run")
    run.add_argument("--model", required=True)
    run.add_argument("--revision", required=True)
    run.add_argument("--out", required=True)
    run.add_argument("--seeds", type=int, nargs="+", default=list(SEEDS))
    sc = sub.add_parser("score")
    sc.add_argument("--model", required=True)
    sc.add_argument("--arm", choices=("base", "untrained", "adapter"), required=True)
    sc.add_argument("--adapter")
    sc.add_argument("--seed", type=int, default=0)
    sc.add_argument("--json", required=True)
    args = parser.parse_args()
    _run_main(args) if args.mode == "run" else _score_main(args)


if __name__ == "__main__":
    main()
