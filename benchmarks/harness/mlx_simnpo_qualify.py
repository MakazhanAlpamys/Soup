#!/usr/bin/env python3
"""Apple Silicon qualification of native SimNPO unlearning on MLX (#2005).

Drives ``MLXSimNPOTrainerWrapper`` through ``build_trainer`` on a real
Llama-architecture checkpoint, then measures the per-token negative
log-likelihood of four fixed row sets under three arms, each scored in a fresh
process:

- ``base``: the checkpoint as loaded;
- ``untrained``: the checkpoint with the run's LoRA layers attached
  (``adapter_config.json``'s ``lora_parameters``, ``mx.random`` seeded with the
  run's seed) and not trained, the control for the LoRA plumbing itself;
- ``adapter``: the checkpoint with the trained adapter loaded by
  ``mlx_lm.load(base, adapter_path=...)``.

The rule this run is judged by is written in
``benchmarks/run-2005-mlx-simnpo-m6.md`` and is applied here unchanged by
:func:`verdict`. The row sets are generated by this file, so a run on another
machine scores the same rows.

Every row is tokenized by ``build_unlearn_example``, the trainer's own
tokenization (its parity with the transformers path's ``_tokenize_pair`` is a
test in ``tests/test_mlx_unlearn.py``), and scored one row at a time with no
padding: float32 logits, a NumPy float64 log-softmax, the target tokens only.

Requires Apple Silicon and ``pip install -e ".[mlx]"``. Downloads nothing: pass
a local snapshot directory as ``--model``.

Usage:
    python mlx_simnpo_qualify.py run --model <snapshot dir> --revision <sha> --out <dir>
"""

